// Тесты детерминированных правил генерации.
//
// Отдельная ловушка, на которую в этом проекте уже попадались дважды:
// \b в JS не работает с кириллицей (\w — это [A-Za-z0-9_]), поэтому границы
// слов задаются явными классами [а-яё]. Тесты ниже её и стерегут.
const { readSource, loadConstArray, makeSuite, assert, assertEqual } = require('./helpers');

const t = makeSuite('ГЕНЕРАЦИЯ: ТЕКСТЫ');

// ─── Детектор книжных реплик ───────────────────────────────────
const LITERARY = loadConstArray('LITERARY_MARKERS');
const hits = (s) => LITERARY.reduce((n, re) => n + (re.test(s) ? 1 : 0), 0);

// Реальные реплики из генераций, которые пришлось переписывать
const BOOKISH = [
  'Я звоню, чтобы обсудить возможность реструктуризации вашего долга. У вас есть время?',
  'Ваш текущий долг составляет 500000. Как вы себя чувствуете с этим долгом?',
  'Понимаю, это может быть сложно. Предлагаем реструктуризировать данный долг.',
  'Это действительно важно. Нельзя упускать из виду.',
  'Мы здесь, чтобы помочь вам.',
  'Я представляю банк. Свяжитесь с нами напрямую.',
  'Оплату можно осуществить через приложение.',
  'При необходимости предоставим подробную информацию.',
  'Будьте уверены, мы ценим вас как клиента.',
  'Это поможет снизить долговую нагрузку.'
];

const SPOKEN = [
  'Звоню по вашей рассрочке — можем уменьшить платёж. Минута есть?',
  'По договору за вами 500000 сум. Получится закрыть в этом месяце?',
  'Понимаю. Разобьём сумму на месяцы — платёж станет меньше.',
  'Оплатить можно в приложении или в любом отделении.',
  'Хорошо, перезвоню завтра. Всего доброго!',
  'Я голосовой помощник, но вопрос решу сам.',
  'Спасибо, согласие записала. Специалист свяжется с вами.'
];

t('книжные реплики распознаются', () => {
  BOOKISH.forEach(s => assert(hits(s) > 0, `не поймано: ${s.slice(0, 60)}`));
});

t('живые реплики не задеваются', () => {
  SPOKEN.forEach(s => assertEqual(hits(s), 0, `ложное срабатывание: ${s.slice(0, 60)}`));
});

t('канцелярское «данный» ловится, существительное «данные» — нет', () => {
  const re = LITERARY.find(r => String(r).includes('данн'));
  [['данный долг', true], ['с данным долгом', true], ['данной суммы', true]]
    .forEach(([s, want]) => assertEqual(re.test(s), want, `«${s}»`));
  // ловушка: «данные» это обычное существительное в банковском скрипте
  [['данные карты', false], ['ваши данные в порядке', false],
   ['по данным банка', false], ['преданный клиент', false]]
    .forEach(([s, want]) => assertEqual(re.test(s), want, `«${s}»`));
});

// ─── Детектор языковых пометок в заголовках ────────────────────
// Модель раздваивала схему на «Приветствие (рус)» + «Приветствие (уз)»
// вместо одного блока с полями ru и uz.
t('пометки языка в заголовках распознаются', () => {
  const src = readSource('script.js');
  const anchor = '.filter(b => /';
  const i = src.indexOf(anchor, src.indexOf('const langTitles'));
  assert(i > 0, 'регулярка langTitles не найдена');
  const start = i + anchor.length - 1;
  const end = src.indexOf('.test(String(b.title', start);
  const RE = eval(src.slice(start, end).trim());

  ['Приветствие (рус)', 'Приветствие (уз)', 'Какой раз повторяет? (РУС)',
   'Нет денег (рус, 1 раз)', 'Kim siz? (uz)', 'Qaysi savol? (UZ, 2)']
    .forEach(s => assert(RE.test(s), `не поймано: ${s}`));

  // ловушки: слова, начинающиеся так же, но безобидные
  ['Приветствие', 'Кто вы?', 'Хочу (узнать условия)', 'Оплата (рублями)', 'Отказ']
    .forEach(s => assert(!RE.test(s), `ложное срабатывание: ${s}`));
});

// ─── Промпт не должен учить модель дублировать схему ───────────
t('пример ромба сводит обе языковые ветки в один блок', () => {
  const src = readSource('script.js');
  assert(!/"label":"Уз","next":"uz_path"/.test(src),
    'в промпте остался пример с РАЗНЫМИ целями веток — он и порождал двойную схему');
  assert(/ОДИН БЛОК — ОБА ЯЗЫКА/.test(src), 'нет правила про один блок на два языка');
});

t('сентинел авто-апгрейда промптов совпадает с текстом промпта', () => {
  const src = readSource('script.js');
  const m = src.match(/if \(!\/([^/]+)\/\.test\(gs\)\)/);
  assert(m, 'проверка свежести generate_system не найдена');
  const sentinel = m[1];
  // сентинел обязан встречаться в самом промпте, иначе апгрейд крутится вечно
  const occurrences = src.split(sentinel).length - 1;
  assert(occurrences >= 2, `сентинел «${sentinel}» не найден в тексте промпта — авто-апгрейд зациклится`);
});

module.exports = t;
